/// The table: language name → keywords.
const TABLE: &[(&str, &[&[&str]])] = &[
    ("Rust", &[RUST]),
    ("Python", &[PYTHON]),
    ("JavaScript", &[JAVASCRIPT]),
    ("TypeScript", &[JAVASCRIPT, TYPESCRIPT_EXTRA]),
    ("TypeScriptReact", &[JAVASCRIPT, TYPESCRIPT_EXTRA]),
    ("Go", &[GO]),
    ("C", &[C]),
    ("C++", &[C, CPP_EXTRA]),
    ("C#", &[CSHARP]),
    ("Java", &[JAVA]),
    ("Kotlin", &[KOTLIN]),
    ("Swift", &[SWIFT]),
    ("PHP", &[PHP]),
    ("Ruby", &[RUBY]),
    ("Lua", &[LUA]),
    ("SQL", &[SQL]),
    ("Bourne Again Shell (bash)", &[SHELL]),
];

/// The keywords of `language` (none for languages not in the table).
pub fn keywords(language: &str) -> impl Iterator<Item = &'static str> {
    TABLE
        .iter()
        .find(|(name, _)| *name == language)
        .into_iter()
        .flat_map(|(_, lists)| lists.iter().flat_map(|l| l.iter().copied()))
        .filter(|w| w.chars().count() > 2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_entry_names_a_known_language() {
        let names = crate::Registry::load().language_names();
        for (name, _) in TABLE {
            assert!(names.iter().any(|n| n == name), "unknown language {name}");
        }
        assert!(keywords("Rust").any(|k| k == "match"));
        assert!(
            !keywords("Rust").any(|k| k == "fn"),
            "short words are left out"
        );
        assert!(keywords("C++").any(|k| k == "nullptr") && keywords("C++").any(|k| k == "sizeof"));
        assert_eq!(keywords("Plain Text").count(), 0);
    }
}
